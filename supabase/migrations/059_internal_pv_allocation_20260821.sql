-- 059_internal_pv_allocation_20260821.sql
--
-- The catalog PV is split into two explicit snapshots:
--   * pv_per_bottle: participant-facing commissionable PV (80% of total PV)
--   * internal_pv_per_bottle: internal marketing/management allocation (20%)
--
-- The internal allocation is not a participant commission and is never used by
-- write_commission_ledger. It is recorded only after an order is paid, through
-- record_internal_pv_allocations(), and is readable only by the founder and
-- Ruth Karimi.
--
-- Existing order_items are historical immutable snapshots. New order items
-- snapshot internal_pv separately; old rows remain at 0 and are not rewritten.

BEGIN;

-- -----------------------------------------------------------------------------
-- Catalog and order snapshots
-- -----------------------------------------------------------------------------

ALTER TABLE public.product_variants
  ADD COLUMN IF NOT EXISTS internal_pv_per_bottle INTEGER NOT NULL DEFAULT 0;

ALTER TABLE public.order_items
  ADD COLUMN IF NOT EXISTS internal_pv INTEGER NOT NULL DEFAULT 0;

ALTER TABLE public.product_variants
  DROP CONSTRAINT IF EXISTS product_variants_internal_pv_per_bottle_check;
ALTER TABLE public.product_variants
  ADD CONSTRAINT product_variants_internal_pv_per_bottle_check
  CHECK (internal_pv_per_bottle >= 0);

ALTER TABLE public.order_items
  DROP CONSTRAINT IF EXISTS order_items_internal_pv_check;
ALTER TABLE public.order_items
  ADD CONSTRAINT order_items_internal_pv_check
  CHECK (internal_pv >= 0);

-- Convert the current catalog snapshot. When the dynamic-PV helper from
-- migration 057 already exists, derive both shares from distributor price so
-- applying 057 before 059 cannot reduce the participant PV twice. Otherwise
-- convert the existing full-PV snapshot once. Both branches are idempotent.
DO $$
BEGIN
  IF to_regprocedure('public.pv_from_distributor_price_minor(bigint)') IS NOT NULL THEN
    UPDATE public.product_variants
       SET internal_pv_per_bottle = total.total_pv - ROUND(total.total_pv * 0.80)::INTEGER,
           pv_per_bottle = ROUND(total.total_pv * 0.80)::INTEGER
      FROM (
        SELECT id,
               public.pv_from_distributor_price_minor(distributor_price_minor) AS total_pv
          FROM public.product_variants
      ) AS total
     WHERE public.product_variants.id = total.id;
  ELSE
    UPDATE public.product_variants
       SET internal_pv_per_bottle = ROUND(pv_per_bottle * 0.25)::INTEGER,
           pv_per_bottle = ROUND(pv_per_bottle * 0.80)::INTEGER
     WHERE internal_pv_per_bottle = 0
       AND pv_per_bottle > 0;
  END IF;
END;
$$;

COMMENT ON COLUMN public.product_variants.pv_per_bottle IS
  'Participant-facing commissionable PV per bottle. The commission engine uses this snapshot only.';
COMMENT ON COLUMN public.product_variants.internal_pv_per_bottle IS
  'Internal marketing/management PV per bottle. Hidden from participants and ordinary admins.';
COMMENT ON COLUMN public.order_items.commission_pv IS
  'Participant-facing commissionable PV snapshot for this order line.';
COMMENT ON COLUMN public.order_items.internal_pv IS
  'Internal marketing/management PV snapshot for this order line. Not participant commission.';

-- -----------------------------------------------------------------------------
-- Internal allocation ledger
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.internal_pv_allocations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
  source_order_item_id BIGINT NOT NULL REFERENCES public.order_items(id) ON DELETE RESTRICT,
  variant_id BIGINT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  internal_pv INTEGER NOT NULL CHECK (internal_pv > 0),
  allocation_type TEXT NOT NULL DEFAULT 'marketing_management'
    CHECK (allocation_type = 'marketing_management'),
  allocated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (source_order_item_id, allocation_type)
);

CREATE INDEX IF NOT EXISTS internal_pv_allocations_order_idx
  ON public.internal_pv_allocations (source_order_id, allocated_at DESC);
CREATE INDEX IF NOT EXISTS internal_pv_allocations_variant_idx
  ON public.internal_pv_allocations (variant_id, allocated_at DESC);

COMMENT ON TABLE public.internal_pv_allocations IS
  'Paid-order internal marketing/management PV allocations. Restricted to the founder and Ruth Karimi.';

