RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT auth.uid() IN (
    '41c9d33c-42d1-4c7a-88d0-a275cc517853'::uuid,
    'dedfac7a-fb6f-457d-9ed7-7712c6e1f93e'::uuid
  )
  AND EXISTS (
    SELECT 1
      FROM public.user_roles ur
     WHERE ur.user_id = auth.uid()
       AND ur.role = 'superadmin'::public.user_role
       AND ur.revoked_at IS NULL
  );
$$;

