-- -----------------------------------------------------------------------------
-- Idempotent paid-order recorder
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.record_internal_pv_allocations(p_order_id BIGINT)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_status public.order_status;
  v_count INTEGER := 0;
BEGIN
  SELECT status
    INTO v_status
    FROM public.orders
   WHERE id = p_order_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'order % not found', p_order_id USING ERRCODE = 'no_data_found';
  END IF;

  IF v_status <> 'paid' THEN
    RAISE EXCEPTION 'order % is not paid (status=%)', p_order_id, v_status
      USING ERRCODE = 'invalid_parameter_value';
  END IF;

  INSERT INTO public.internal_pv_allocations (
    source_order_id,
    source_order_item_id,
    variant_id,
    quantity,
    internal_pv,
    allocation_type,
    allocated_at
  )
  SELECT
    oi.order_id,
    oi.id,
    oi.variant_id,
    oi.quantity,
    oi.internal_pv,
    'marketing_management',
    COALESCE(o.paid_at, NOW())
    FROM public.order_items oi
    JOIN public.orders o ON o.id = oi.order_id
   WHERE oi.order_id = p_order_id
     AND oi.internal_pv > 0
  ON CONFLICT (source_order_item_id, allocation_type) DO NOTHING;

  GET DIAGNOSTICS v_count = ROW_COUNT;

  INSERT INTO public.audit_log (
    actor_id, action, resource_type, resource_id, after_data
  ) VALUES (
    NULL,
    'internal_pv.allocations_written',
    'orders',
    p_order_id::TEXT,
    jsonb_build_object(
      'rows_written', v_count,
      'internal_pv', COALESCE((
        SELECT SUM(internal_pv)
          FROM public.order_items
         WHERE order_id = p_order_id
           AND internal_pv > 0
      ), 0)
    )
  );

  RETURN v_count;
END;
$$;

REVOKE ALL ON FUNCTION public.record_internal_pv_allocations(BIGINT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.record_internal_pv_allocations(BIGINT) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_internal_pv_allocations(BIGINT) TO service_role;

NOTIFY pgrst, 'reload schema';

COMMIT;
